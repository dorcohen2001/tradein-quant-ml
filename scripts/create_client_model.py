def render(template: str, **tokens: str) -> str:
    out = template
    for name, value in tokens.items():
        out = out.replace(f"__{name}__", str(value))
    return out


# ===========================================================================
# Registry surgery
# ===========================================================================
def _read_registry() -> str:
    with open(REGISTRY_PATH, "r", encoding="utf-8") as fh:
        return fh.read()


def _write_registry(text: str) -> None:
    """Write via a temp file + replace, so an interrupted edit can never leave
    a half-written registry -- which every model's config imports at startup."""
    tmp = f"{REGISTRY_PATH}.tmp"
    with open(tmp, "w", encoding="utf-8", newline="") as fh:
        fh.write(text)
    os.replace(tmp, REGISTRY_PATH)


def register(full_key: str, name: str, interval: int, description: str,
             dedicated: bool = False) -> None:
    src = _read_registry()
    if END_MARKER not in src:
        raise RuntimeError(
            f"{REGISTRY_PATH} has no '{END_MARKER.strip()}' marker -- refusing to guess "
            f"where a client entry belongs."
        )
    if f"client:{full_key} >>>" in src:
        raise RuntimeError(f"{full_key} is already registered; use --remove first.")

    entry = render(T_REGISTRY_ENTRY, FULL_KEY=full_key, NAME=name,
                   INTERVAL=interval, DESCRIPTION=description,
                   DEDICATED=str(bool(dedicated)))
    _write_registry(src.replace(END_MARKER, entry + END_MARKER, 1))


def deregister(full_key: str) -> bool:
    src = _read_registry()
    begin = f"    # >>> client:{full_key} >>>"
    end = f"    # <<< client:{full_key} <<<"
    if begin not in src or end not in src:
        return False
    head, _, rest = src.partition(begin)
    _, _, tail = rest.partition(end)
    _write_registry(head + tail.lstrip("\n"))
    return True


