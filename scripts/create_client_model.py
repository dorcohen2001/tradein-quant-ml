@dataclass
class ClientSetup:
    """One qualifying setup. The field names match what live_runner.py and
    `core.utils.chart_attachment` expect, so a setup renders and logs without
    any translation layer."""

    ticker: str
    asset_class: str
    direction: str          # "LONG" | "SHORT"
    entry_low: float
    entry_high: float
    stop: float
    target1: float
    target2: float
    rr1: float
    rr2: float
    thesis: str
    score: float = 0.0
    fib_zone: tuple[float, float] | None = None
    supports: list[float] = field(default_factory=list)
    resistances: list[float] = field(default_factory=list)


def evaluate(ticker: str, asset_class: str, df: pd.DataFrame) -> tuple[ClientSetup | None, str]:
    """Decide whether `df` presents a setup right now.

    Returns `(setup, reason)`. `setup` is None when nothing qualifies, and
    `reason` explains why -- the runner logs those, which is what makes a quiet
    strategy debuggable instead of mysterious.

    Contract: use ONLY bars up to the last row. Reading ahead is the classic
    backtest-vs-live divergence, and it is silent.
    """
    if df is None or len(df) < 60:
        return None, f"{ticker}: not enough history ({0 if df is None else len(df)} bars)"

    data = add_indicators(df)
    last = data.iloc[-1]

    atr_now = float(last["ATR"])
    price = float(last["Close"])
    if not atr_now or atr_now <= 0 or price <= 0:
        return None, f"{ticker}: no usable ATR/price"

    # --- PLACEHOLDER RULE: trend + pullback -------------------------------
    uptrend = bool(last["EMA_FAST"] > last["EMA_SLOW"])
    downtrend = bool(last["EMA_FAST"] < last["EMA_SLOW"])
    rsi_now = float(last["RSI"])

    if uptrend and rsi_now < 45:
        direction = "LONG"
    elif downtrend and rsi_now > 55:
        direction = "SHORT"
    else:
        return None, f"{ticker}: no trend/pullback alignment (RSI {rsi_now:.1f})"

    if direction == "LONG":
        entry_low, entry_high = price * 0.999, price * 1.001
        stop = price - STOP_ATR_MULT * atr_now
        target1 = price + TP1_ATR_MULT * atr_now
        target2 = price + TP2_ATR_MULT * atr_now
    else:
        entry_low, entry_high = price * 0.999, price * 1.001
        stop = price + STOP_ATR_MULT * atr_now
        target1 = price - TP1_ATR_MULT * atr_now
        target2 = price - TP2_ATR_MULT * atr_now

    risk = abs(price - stop)
    if risk <= 0:
        return None, f"{ticker}: degenerate stop distance"
    rr1 = abs(target1 - price) / risk
    rr2 = abs(target2 - price) / risk
    if rr1 < MIN_RISK_REWARD:
        return None, f"{ticker}: R:R {rr1:.2f} below the {MIN_RISK_REWARD} floor"

    setup = ClientSetup(
        ticker=ticker, asset_class=asset_class, direction=direction,
        entry_low=entry_low, entry_high=entry_high,
        stop=stop, target1=target1, target2=target2, rr1=rr1, rr2=rr2,
        thesis=(f"{direction} pullback in a {'up' if uptrend else 'down'}trend "
                f"(EMA20/50), RSI {rsi_now:.1f}, ATR {atr_now:.4g}"),
        score=round(min(100.0, rr1 * 25), 1),
    )
    return setup, "ok"
