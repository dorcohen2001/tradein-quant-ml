def _full_key(key: str) -> str:
    key = key.strip().lower()
    return key if key.startswith("client_") else f"client_{key}"


def _do_create(args) -> int:
    supplied = args.key.strip()
    raw = supplied.lower()
    if raw != supplied:
        # Announced rather than silent: the key becomes a directory name and is
        # baked into every runtime filename, so the user must see the value
        # actually being used -- not discover it later when looking for a file
        # that is not where they expected.
        print(f"[note] key normalised to lowercase: {supplied!r} -> {raw!r}")
    if not VALID_KEY.match(raw):
        print(f"[error] invalid key {raw!r}: use lowercase letters, digits and underscores, "
              f"starting with a letter.", file=sys.stderr)
        return 1
    if raw in RESERVED_KEYS:
        print(f"[error] {raw!r} is reserved.", file=sys.stderr)
        return 1

    full_key = _full_key(raw)

    # Collision check against the LIVE registry, not just the filesystem: a key
    # that resolves to an existing model would share its trade store.
    from core.registry import model_keys
    if full_key in model_keys():
        print(f"[error] {full_key!r} is already registered. Use --remove first.", file=sys.stderr)
        return 1

    model_dir = os.path.join(MODELS_DIR, full_key)
    if os.path.exists(model_dir) and not args.force:
        print(f"[error] {model_dir} already exists. Use --force to overwrite.", file=sys.stderr)
        return 1

    description = args.description or f"Client strategy on {args.timeframe} {args.asset_class}."

    print(f"Scaffolding {full_key} ({args.name})")

    # --force re-renders every template over whatever is there, which puts the
    # placeholder rule back over a tuned `strategy/screener.py`. Archive first,
    # and abort if the archive cannot be written -- overwriting the only copy
    # of a client's strategy is not something to do on a best-effort basis.
    if os.path.isdir(model_dir):
        print(f"  --force: {full_key} already exists, archiving before overwrite")
        try:
            archive_model_dir(model_dir, full_key, "preoverwrite")
        except Exception as exc:
            print(f"[error] could not archive {model_dir} ({exc}); refusing to overwrite.",
                  file=sys.stderr)
            return 1
    scaffold(full_key, args.name, args.interval, args.timeframe, args.asset_class,
             description, dedicated=args.dedicated_route)

    try:
        register(full_key, args.name, args.interval, description, dedicated=args.dedicated_route)
        route_mode = "dedicated route" if args.dedicated_route else "shared primary hub"
        print(f"  registered {full_key} in core/registry.py (stage=incubating, {route_mode})")
    except Exception as exc:
        # Roll the directory back so a failed run does not leave an unregistered
        # tree that later collides with a retry.
        print(f"[error] registration failed: {exc}", file=sys.stderr)
        shutil.rmtree(model_dir, ignore_errors=True)
        print(f"[error] removed {model_dir} to leave a clean state.", file=sys.stderr)
        return 1

    print_env_guide(full_key, dedicated=args.dedicated_route)
    print()
    print("Next steps:")
    print(f"  1. Set the two env vars above, then verify the route resolves.")
    print(f"  2. Edit models/{full_key}/strategy/screener.py -- that is the strategy.")
    print(f"  3. Dry run:  cd models/{full_key} && python live_runner.py --once --dry-run")
    print(f"  4. Schedule: python run_supervisor.py --models {full_key} --dry-run")
    print("  5. Graduate when the checklist in docs/CLIENT_ONBOARDING_GUIDE.md is met.")
    return 0


def _do_remove(key: str) -> int:
    full_key = _full_key(key)
    model_dir = os.path.join(MODELS_DIR, full_key)

    removed_entry = deregister(full_key)
    if removed_entry:
        print(f"  deregistered {full_key} from core/registry.py")
    else:
        print(f"  {full_key} was not registered (nothing to deregister)")

    if os.path.isdir(model_dir):
        # Archive BEFORE deleting, and abort if that fails. `strategy/screener.py`
        # is the client's own work; removing a scaffold is not a decision to
        # destroy it, and an uncommitted tuning session is otherwise gone.
        try:
            archive_model_dir(model_dir, full_key, "preremove")
        except Exception as exc:
            print(f"[error] could not archive {model_dir} ({exc}); NOT deleting it. "
                  f"The registry entry was already removed -- re-register with the "
                  f"generator, or fix the archive path and re-run --remove.", file=sys.stderr)
            return 1
        shutil.rmtree(model_dir)
        print(f"  deleted models/{full_key}/")
    else:
        print(f"  models/{full_key}/ does not exist")

    # Runtime state is deliberately NOT deleted. It is the client's trade
    # history, it is the one thing that cannot be regenerated, and removing a
    # scaffold is not a statement about the data it produced.
    print(f"  runtime artifacts for {full_key} were left in place "
          f"(trade store, journal, charts, funnel exports)")
    print(f"  source tree archived under backups/client_models/ -- unzip it into "
          f"models/ and re-run the generator to restore")
    return 0


